"""Regenerate lib/core/i18n/strings_hi.dart from the JSON in this folder.

    python tool/i18n/generate.py

The English string in the widget is the key, so there is nothing to keep in
sync by hand: `keys.py` reads every literal the code marks with `.tr`,
`.trf` or `Tr.plural`, and this script checks the translations against that
list before it writes anything.

Checks, all fatal:
  * a key nobody asks for (a typo, or copy that has since been reworded)
  * {0}/{1} placeholders that differ between English and Hindi
  * a different number of \\n escapes, which would silently reflow a label

A key with no translation is *not* fatal. `Tr.of` falls through to the
English it was handed, so an untranslated string reads in English instead
of breaking the screen. Proper nouns are left out on purpose.
"""

import io, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "lib", "core", "i18n", "strings_hi.dart")

sys.path.insert(0, HERE)
import keys as keyscan  # noqa: E402


def load():
    tr = {}
    for name in sorted(os.listdir(HERE)):
        if not re.fullmatch(r"hi_\d+\.json", name):
            continue
        part = json.load(io.open(os.path.join(HERE, name), encoding="utf-8"))
        for k, v in part.items():
            if k in tr and tr[k] != v:
                print("  ! %s redefines %r" % (name, k))
            tr[k] = v
    return tr


def dart(s):
    """Emit `s` as Dart source, keeping its escapes byte for byte.

    The keys are stored in their *source* spelling, so a `\\n` here is the
    two characters backslash-n. Written into Dart source unchanged, the
    compiler turns it back into the newline the running code will look up.
    """
    if "'" not in s:
        return "'" + s + "'"
    if '"' not in s:
        return '"' + s + '"'
    return "'" + s.replace("'", "\\'") + "'"


def main():
    wanted = keyscan.scan(os.path.join(ROOT, "lib"))
    tr = load()

    ph = re.compile(r"\{\d+\}")
    nl = re.compile(r"\\n")

    problems = []
    for k in sorted(set(tr) - wanted):
        # `km` is nested inside another literal's interpolation, so the
        # scanner cannot see it even though the code does use it.
        if k != "km":
            problems.append("no code asks for %r" % k)
    for k, v in sorted(tr.items()):
        if sorted(ph.findall(k)) != sorted(ph.findall(v)):
            problems.append("placeholders differ: %r -> %r" % (k, v))
        if len(nl.findall(k)) != len(nl.findall(v)):
            problems.append("line breaks differ: %r -> %r" % (k, v))

    covered = len(wanted & set(tr))
    print("keys in code : %d" % len(wanted))
    print("translated   : %d" % len(tr))
    print("covered      : %d (%.0f%%)" % (covered, 100 * covered / len(wanted)))

    missing = sorted(wanted - set(tr))
    io.open(os.path.join(HERE, "untranslated.txt"), "w",
            encoding="utf-8").write("\n".join(missing) + "\n")
    print("untranslated : %d (see tool/i18n/untranslated.txt)" % len(missing))

    if problems:
        print("\n%d problem(s):" % len(problems))
        for p in problems:
            print("   " + p)
        return 1

    head = [
        "// GENERATED by tool/i18n/generate.py — edit tool/i18n/hi_*.json,",
        "// then run `python tool/i18n/generate.py`. Do not edit this file.",
        "",
        "/// Hindi copy, keyed by the English source text.",
        "///",
        "/// A missing key is not an error: [Tr.of] falls through to the",
        "/// English it was given, so an untranslated string reads in English",
        "/// rather than breaking the screen. Makes, models, the photo credits",
        "/// and the seeded demo rows are left out deliberately — a proper noun",
        "/// should not change with the language.",
        "///",
        "/// The workshop's own vocabulary is kept the way a mechanic says it:",
        "/// जॉब कार्ड, स्पेयर, सर्विस. Rendering those in literary Hindi would",
        "/// make the console harder to read, not easier.",
        "const Map<String, String> stringsHi = <String, String>{",
    ]
    body = ["  %s: %s," % (dart(k), dart(tr[k]))
            for k in sorted(tr, key=lambda s: s.lower())]
    io.open(OUT, "w", encoding="utf-8", newline="\r\n").write(
        "\n".join(head + body + ["};"]) + "\n")
    print("\nwrote " + os.path.relpath(OUT, ROOT).replace("\\", "/"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
